-- Nuevo: cuando un alimentador huerfano se agrega recien al maestro
-- ALIMENTADORES, corrige de una sola vez todas las filas de IRREGULARIDADES
-- que estaban esperando por el (ORIGEN='NO INFORMADO') -- sin esto, esas
-- filas quedarian con ORIGEN desactualizado hasta que alguien las edite a
-- mano (pedido explicito: se autocorrige solo, sin intervencion manual).
CREATE TRIGGER trg_alim_ins_origen AFTER INSERT ON ALIMENTADORES BEGIN
    UPDATE IRREGULARIDADES SET alimentador_id=NEW.id, ORIGEN='PROY-101'
    WHERE UPPER(ALIMENTADOR)=UPPER(NEW.ALIMENTADOR) AND ORIGEN='NO INFORMADO';
END;

