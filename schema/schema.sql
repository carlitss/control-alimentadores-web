            UPDATE SOSPECHAS_MT SET PERIODO_PLANIF=NEW.MES_PLANIFICADO WHERE ALIMENTADOR=NEW.ALIMENTADOR;
            UPDATE SOSPECHAS_BT SET PERIODO_PLANIF=COALESCE(NEW.MES_PLANIFICADO,'') WHERE ALIMENTADOR=NEW.ALIMENTADOR;
        END;

