CREATE TABLE IRREGULARIDADES (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    -- Nullable (antes NOT NULL): una fila puede llegar con un ALIMENTADOR
    -- que todavia no existe en el maestro (ver ORIGEN mas abajo) -- no se
    -- descarta la fila por eso, se guarda con alimentador_id=NULL hasta
    -- que el maestro lo tenga.
    alimentador_id INTEGER REFERENCES ALIMENTADORES(id),
    ALIMENTADOR TEXT NOT NULL,
    NODO INTEGER NOT NULL,
    -- Ex CONCA, renombrada a KEY (pedido explicito) -- es la clave real de
    -- esta tabla, viene tal cual del Excel origen (no se deriva en este
    -- pipeline), por eso es estable entre cargas. "KEY" es palabra
    -- reservada de SQL: toda referencia en el codigo la cita entre
    -- comillas dobles.
    "KEY" TEXT NOT NULL UNIQUE,
    SUM_CLIENTE INTEGER,
    COD_PUNTO_MEDICION TEXT,
    CATEGORIA TEXT,
    TIPO_HURTO TEXT,
    TENSION TEXT,
    TIPO_CLIENTE TEXT,
    CONDICION_CLIENTE TEXT,
    FECHA_ASIG_INSP TEXT,
    FECHA_NORMALIZACION TEXT,
    -- Auditado junto con el fix de SOSPECHAS_BT.PERDIDA_KWH (operando vacio
    -- tratado como 0): NO aplica aca. Una fecha faltante no es "cero dias",
    -- es "no se puede calcular" -- tratarla como 0 daria una diferencia de
    -- dias falsa, no "sin dato". Se deja exigiendo ambas fechas.
    DIAS_CIERRE INTEGER GENERATED ALWAYS AS (
        CASE WHEN FECHA_NORMALIZACION IS NOT NULL AND FECHA_ASIG_INSP IS NOT NULL
        THEN CAST(julianday(FECHA_NORMALIZACION) - julianday(FECHA_ASIG_INSP) AS INTEGER)
        ELSE NULL END
    ) STORED,
    ESTADO_FOCALIZACION TEXT,
    RECUPERO_MWH REAL,
    MESES_CNR REAL,
    -- Auditado junto con SOSPECHAS_BT.PERDIDA_KWH: NO aplica aca tampoco.
    -- Es un promedio mensual (division) -- sin RECUPERO_MWH o sin MESES_CNR
    -- no hay tasa que calcular ("sin dato" real), tratar cualquiera de los
    -- dos como 0 daria una tasa falsa (0 o division por cero ya evitada).
    RECUPERO_MWH_MES REAL GENERATED ALWAYS AS (
        CASE WHEN MESES_CNR IS NOT NULL AND MESES_CNR != 0 AND RECUPERO_MWH IS NOT NULL
        THEN ROUND(RECUPERO_MWH / MESES_CNR, 4) ELSE NULL END
    ) STORED,
    ESTADO_CNR TEXT,
    IMPACTO_ANO_MWH REAL,
    MOTIVO_RECHAZO TEXT,
    OBSERVACIONES TEXT,
    -- Columna nueva, mantenida por trigger (trg_irr_ins/trg_irr_upd), NO
    -- por la app: 'PROY-101' si ALIMENTADOR existe en el maestro
    -- ALIMENTADORES al momento del insert/update, 'NO INFORMADO' si no.
    -- No es GENERATED porque SQLite no permite subqueries en columnas
    -- generadas (necesita mirar OTRA tabla) -- se recalcula via trigger,
    -- mismo patron que ESTADO_RE/PERIODO_PLANIF en SOSPECHAS_BT. Se
    -- autocorrige a 'PROY-101' sin intervencion manual cuando el
    -- alimentador huerfano se agrega despues a ALIMENTADORES, via
    -- trg_alim_ins_origen.
    ORIGEN TEXT,
    ESTADO_REGISTRO TEXT DEFAULT 'ALTA',
    CREADO_POR TEXT DEFAULT 'MIGRACION',
    FECHA_CREACION TEXT DEFAULT (datetime('now','localtime')),
    MODIFICADO_POR TEXT,
    FECHA_MODIFICACION TEXT,
    DADO_DE_BAJA_POR TEXT,
    FECHA_BAJA TEXT,
    MOTIVO_BAJA TEXT
);

