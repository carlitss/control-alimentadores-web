            CASE
                WHEN (COALESCE(TOTAL_IMPEDIMENTOS_LEC,0) + COALESCE(TOTAL_EFECTIVOS_LECTURA,0) + COALESCE(TOTAL_EFECTIVOS_PINZADO,0))
                     = COALESCE(TOTAL_LECTURAS_RECOGER,0)
                THEN 'CERRADO'
                WHEN (COALESCE(TOTAL_IMPEDIMENTOS_LEC,0) + COALESCE(TOTAL_EFECTIVOS_LECTURA,0) + COALESCE(TOTAL_EFECTIVOS_PINZADO,0)) > 0
                     AND (COALESCE(TOTAL_IMPEDIMENTOS_LEC,0) + COALESCE(TOTAL_EFECTIVOS_LECTURA,0) + COALESCE(TOTAL_EFECTIVOS_PINZADO,0))
                         < COALESCE(TOTAL_LECTURAS_RECOGER,0)
                THEN 'EN CURSO'
                ELSE ''
            END
        ) VIRTUAL, ESTADO_INST_TOTAS TEXT GENERATED ALWAYS AS (
            CASE
                WHEN COALESCE(TOTAL_INSTALADOS_TOTA,0) = COALESCE(TOTAL_CASOS_INST_TOTA,0)
                THEN 'CERRADO'
                WHEN (COALESCE(TOTAL_IMP_TOTA,0) + COALESCE(TOTAL_INSTALADOS_TOTA,0)) = COALESCE(TOTAL_CASOS_INST_TOTA,0)
                THEN 'CERRADO CON IMP'
                WHEN (COALESCE(TOTAL_IMP_TOTA,0) + COALESCE(TOTAL_INSTALADOS_TOTA,0)) > 0
                     AND (COALESCE(TOTAL_IMP_TOTA,0) + COALESCE(TOTAL_INSTALADOS_TOTA,0)) < COALESCE(TOTAL_CASOS_INST_TOTA,0)
                THEN 'EN CURSO'
                ELSE ''
            END
        ) VIRTUAL, N_TOTAS INTEGER DEFAULT 0, TOTAS_PENDIENTES INTEGER DEFAULT 0, TOTAL_CLIENTES_MT INTEGER GENERATED ALWAYS AS (
            COALESCE(N_TOTAS,0) + COALESCE(TOTAS_PENDIENTES,0) + COALESCE(CLIENTES_MAX_MT,0)
            + COALESCE(CLIENTES_LIB_PEAJES,0) + COALESCE(CLIENTES_NO_UBI,0)
        ) VIRTUAL);

